const sitemapXml = () => `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${BASE_URL}/</loc>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
  </url>
${FORMATS.map(
  (f) => `  <url>
    <loc>${BASE_URL}/${f.slug}/</loc>
    <changefreq>weekly</changefreq>
    <priority>0.8</priority>
  </url>`,
).join("\n")}
</urlset>
`;

// Cleanup: remove dirs matching our managed slugs AND any legacy pair-route dirs.
const managed = new Set(FORMATS.map((f) => f.slug));
const isPairDir = (name) => /^[a-z]+-to-[a-z]+$/.test(name);
for (const entry of readdirSync(srcDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  if (managed.has(entry.name) || isPairDir(entry.name)) {
    rmSync(resolve(srcDir, entry.name), { recursive: true });
  }
}

// Generate fresh.
for (const format of FORMATS) {
  const dir = resolve(srcDir, format.slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, "index.html"), htmlTemplate(format));
}

writeFileSync(resolve(srcDir, "public/sitemap.xml"), sitemapXml());

console.log(`Generated ${FORMATS.length} format pages + sitemap.`);

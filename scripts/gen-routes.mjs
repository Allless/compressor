#!/usr/bin/env node
import {
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const srcDir = resolve(__dirname, "../src");

// Add more pairs here to grow the SEO surface. Re-run `pnpm gen:routes`.
const ROUTES = [
  { from: "heic", to: "jpg", fromLabel: "HEIC", toLabel: "JPG" },
  { from: "heic", to: "png", fromLabel: "HEIC", toLabel: "PNG" },
  { from: "heic", to: "webp", fromLabel: "HEIC", toLabel: "WebP" },
  { from: "webp", to: "jpg", fromLabel: "WebP", toLabel: "JPG" },
  { from: "webp", to: "png", fromLabel: "WebP", toLabel: "PNG" },
  { from: "png", to: "jpg", fromLabel: "PNG", toLabel: "JPG" },
  { from: "png", to: "webp", fromLabel: "PNG", toLabel: "WebP" },
  { from: "jpg", to: "png", fromLabel: "JPG", toLabel: "PNG" },
  { from: "jpg", to: "webp", fromLabel: "JPG", toLabel: "WebP" },
  { from: "avif", to: "jpg", fromLabel: "AVIF", toLabel: "JPG" },
];

const htmlTemplate = ({ from, to, fromLabel, toLabel }) => `<!doctype html>
<!-- GENERATED by scripts/gen-routes.mjs — edit the generator, not this file. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${fromLabel} to ${toLabel} Converter — Free, In-Browser, No Upload | Lessly</title>
    <meta name="description" content="Convert ${fromLabel} to ${toLabel} directly in your browser. Free, private, no upload — files never leave your device." />
    <meta name="keywords" content="${from} to ${to}, convert ${from} to ${to}, ${from} converter, ${to} converter, free, browser, no upload, private" />
    <meta name="robots" content="index, follow" />
    <link rel="canonical" href="https://allless.github.io/lessly/${from}-to-${to}/" />

    <meta property="og:type" content="website" />
    <meta property="og:url" content="https://allless.github.io/lessly/${from}-to-${to}/" />
    <meta property="og:title" content="${fromLabel} to ${toLabel} Converter — Lessly" />
    <meta property="og:description" content="Convert ${fromLabel} to ${toLabel} in your browser. No upload, fully private." />
    <meta property="og:image" content="https://allless.github.io/lessly/favicon.svg" />

    <meta name="twitter:card" content="summary" />
    <meta name="twitter:title" content="${fromLabel} to ${toLabel} Converter" />
    <meta name="twitter:description" content="Convert ${fromLabel} to ${toLabel} in your browser. No upload." />
    <meta name="twitter:image" content="https://allless.github.io/lessly/favicon.svg" />

    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <link rel="stylesheet" href="/style.css" />

    <script type="application/ld+json">
    {
      "@context": "https://schema.org",
      "@type": "WebApplication",
      "name": "Lessly — ${fromLabel} to ${toLabel} Converter",
      "url": "https://allless.github.io/lessly/${from}-to-${to}/",
      "description": "Convert ${fromLabel} to ${toLabel} in your browser. No upload required.",
      "applicationCategory": "MultimediaApplication",
      "operatingSystem": "Any",
      "offers": { "@type": "Offer", "price": "0", "priceCurrency": "USD" }
    }
    </script>
  </head>
  <body>
    <main id="app">
      <noscript>
        <h1>Convert ${fromLabel} to ${toLabel} — Free Online Converter</h1>
        <p>Convert ${fromLabel} images to ${toLabel} in your browser. No upload, fully private. Please enable JavaScript to use this tool.</p>
      </noscript>
    </main>
    <script type="module" src="/ts/main.tsx"></script>
  </body>
</html>
`;

const sitemapXml = () => `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>https://allless.github.io/lessly/</loc>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
  </url>
${ROUTES.map(
  (r) => `  <url>
    <loc>https://allless.github.io/lessly/${r.from}-to-${r.to}/</loc>
    <changefreq>weekly</changefreq>
    <priority>0.8</priority>
  </url>`,
).join("\n")}
</urlset>
`;

// Wipe existing route dirs (they're all generated).
const isRouteDir = (name) => /^[a-z]+-to-[a-z]+$/.test(name);
for (const entry of readdirSync(srcDir, { withFileTypes: true })) {
  if (entry.isDirectory() && isRouteDir(entry.name)) {
    rmSync(resolve(srcDir, entry.name), { recursive: true });
  }
}

// Generate fresh.
for (const route of ROUTES) {
  const dir = resolve(srcDir, `${route.from}-to-${route.to}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, "index.html"), htmlTemplate(route));
}

writeFileSync(resolve(srcDir, "public/sitemap.xml"), sitemapXml());

console.log(`Generated ${ROUTES.length} route pages + sitemap.`);
